function getInitialLanguage(): string {
  // 中文：产品默认使用中文，只有用户主动切换后才持久化其他语言。
  if (typeof window === 'undefined') return 'zh-CN'
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (stored && LANGUAGE_OPTIONS.some((option) => option.code === stored)) return stored
  } catch {
    // 中文：存储不可用时回退默认语言，不能让初始化阶段卡住加载层。
  }
  return 'zh-CN'
}

void i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: getInitialLanguage(),
    fallbackLng: 'zh-CN',
    supportedLngs: LANGUAGE_OPTIONS.map((option) => option.code),
    interpolation: { escapeValue: false },
    initAsync: false,
    returnNull: false,
  })

i18n.on('languageChanged', (language) => {
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
  } catch {
    // 中文：语言切换仍在当前会话生效，持久化失败不影响页面使用。
  }
  if (typeof document !== 'undefined') document.documentElement.lang = language === 'en-US' ? 'en' : 'zh-CN'
})

export type AppLanguage = typeof LANGUAGE_OPTIONS[number]['code']

export function getActiveLanguage(): AppLanguage {
  return i18n.language.startsWith('en') ? 'en-US' : 'zh-CN'
}

export function getActiveLocale(): string {
  return getActiveLanguage()
}

export default i18n
